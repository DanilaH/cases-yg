import fs from 'node:fs/promises';
import path from 'node:path';

const BUNDLE_COUNT = 6;
const MAGIC = Buffer.from('MPTPAK01', 'ascii');
const HEADER_BYTES = MAGIC.length + 4;
const sourcePath = path.resolve('src/game/data/artAssets.ts');
const outputDir = path.resolve('public/assets/bundles');
const generatedTsPath = path.resolve('src/game/data/runtimeAssetBundles.generated.ts');
const reportPath = path.resolve('.asset-build/runtime-bundles/report.json');

const source = await fs.readFile(sourcePath, 'utf8');

const staticBlock = source.match(/const STATIC_ART_PATHS = \{([\s\S]*?)\n\} as const;/)?.[1];
if (!staticBlock) throw new Error('Could not locate STATIC_ART_PATHS in artAssets.ts');

const staticEntries = [];
for (const match of staticBlock.matchAll(/\s*'([^']+)'\s*:\s*'([^']+\.webp)'\s*,?/g)) {
  const [, id, assetPath] = match;
  staticEntries.push({
    textureKey: `art:static:${id}`,
    assetPath,
    filePath: path.resolve('public', assetPath),
  });
}

const collectibleBlock = source.match(/AVAILABLE_COLLECTIBLE_ART_IDS = new Set<string>\(\[([\s\S]*?)\n\]\);/)?.[1];
if (!collectibleBlock) throw new Error('Could not locate AVAILABLE_COLLECTIBLE_ART_IDS in artAssets.ts');

const collectibleEntries = [];
for (const match of collectibleBlock.matchAll(/'([^']+)'/g)) {
  const id = match[1];
  const assetPath = `assets/collectibles/${id}.webp`;
  collectibleEntries.push({
    textureKey: `art:collectible:${id}`,
    assetPath,
    filePath: path.resolve('public', assetPath),
  });
}

const entries = [...staticEntries, ...collectibleEntries];
if (staticEntries.length !== 45) {
  throw new Error(`Expected 45 reviewed static textures, found ${staticEntries.length}`);
}
if (collectibleEntries.length !== 70) {
  throw new Error(`Expected 70 reviewed collectible textures, found ${collectibleEntries.length}`);
}
if (entries.length !== 115) throw new Error(`Expected 115 runtime textures, found ${entries.length}`);

const keys = new Set();
const assetPaths = new Set();
for (const entry of entries) {
  if (keys.has(entry.textureKey)) throw new Error(`Duplicate texture key ${entry.textureKey}`);
  if (assetPaths.has(entry.assetPath)) throw new Error(`Duplicate runtime asset path ${entry.assetPath}`);
  keys.add(entry.textureKey);
  assetPaths.add(entry.assetPath);

  const stat = await fs.stat(entry.filePath);
  if (!stat.isFile()) throw new Error(`Runtime asset is not a file: ${entry.filePath}`);
  entry.bytes = stat.size;
}

// Largest-first greedy balancing makes all six network bundles finish at roughly
// the same time while preserving deterministic output for a given runtime set.
const groups = Array.from({ length: BUNDLE_COUNT }, (_, index) => ({
  index,
  bytes: 0,
  entries: [],
}));
for (const entry of [...entries].sort((left, right) =>
  right.bytes - left.bytes || left.assetPath.localeCompare(right.assetPath),
)) {
  groups.sort((left, right) => left.bytes - right.bytes || left.index - right.index);
  const group = groups[0];
  group.entries.push(entry);
  group.bytes += entry.bytes;
}
groups.sort((left, right) => left.index - right.index);

await fs.rm(outputDir, { recursive: true, force: true });
await fs.mkdir(outputDir, { recursive: true });
await fs.mkdir(path.dirname(reportPath), { recursive: true });

const generatedBundles = [];
let sourceBytes = 0;
let packedBytes = 0;
for (const group of groups) {
  group.entries.sort((left, right) => left.textureKey.localeCompare(right.textureKey));
  let payloadOffset = 0;
  const payloads = [];
  const indexEntries = [];

  for (const entry of group.entries) {
    const data = await fs.readFile(entry.filePath);
    if (data.length !== entry.bytes) throw new Error(`Runtime asset changed while bundling: ${entry.assetPath}`);
    payloads.push(data);
    indexEntries.push({
      textureKey: entry.textureKey,
      assetPath: entry.assetPath,
      offset: payloadOffset,
      length: data.length,
    });
    payloadOffset += data.length;
    sourceBytes += data.length;
  }

  const indexBuffer = Buffer.from(JSON.stringify({ version: 1, entries: indexEntries }), 'utf8');
  const header = Buffer.alloc(HEADER_BYTES);
  MAGIC.copy(header, 0);
  header.writeUInt32LE(indexBuffer.length, MAGIC.length);
  const output = Buffer.concat([header, indexBuffer, ...payloads]);
  const sequence = String(group.index + 1).padStart(2, '0');
  const fileName = `runtime-art-${sequence}.mptpack`;
  await fs.writeFile(path.join(outputDir, fileName), output);
  packedBytes += output.length;
  generatedBundles.push({
    key: `runtime-art-bundle-${sequence}`,
    assetPath: `assets/bundles/${fileName}`,
    textureCount: indexEntries.length,
    sourceBytes: payloadOffset,
    packedBytes: output.length,
  });
}

const generatedTs = `// Generated by tools/assets/build-runtime-bundles.mjs. Do not edit by hand.\n` +
  `export const RUNTIME_ART_BUNDLE_VERSION = 1 as const;\n` +
  `export const RUNTIME_ART_BUNDLE_TEXTURE_COUNT = ${entries.length} as const;\n` +
  `export const RUNTIME_ART_BUNDLES = ${JSON.stringify(generatedBundles, null, 2)} as const;\n`;
await fs.writeFile(generatedTsPath, generatedTs);

const report = {
  version: 1,
  bundleCount: generatedBundles.length,
  textureCount: entries.length,
  staticTextureCount: staticEntries.length,
  collectibleTextureCount: collectibleEntries.length,
  sourceBytes,
  packedBytes,
  overheadBytes: packedBytes - sourceBytes,
  overheadRatio: sourceBytes === 0 ? 0 : (packedBytes - sourceBytes) / sourceBytes,
  bundles: generatedBundles,
};
await fs.writeFile(reportPath, `${JSON.stringify(report, null, 2)}\n`);

console.log(
  `[runtime-bundles] ${entries.length} textures -> ${generatedBundles.length} packs; ` +
  `${(sourceBytes / 1024 / 1024).toFixed(2)} -> ${(packedBytes / 1024 / 1024).toFixed(2)} MiB; ` +
  `overhead ${((report.overheadRatio) * 100).toFixed(3)}%`,
);
for (const bundle of generatedBundles) {
  console.log(
    `  ${bundle.key}: ${bundle.textureCount} textures, ${(bundle.packedBytes / 1024 / 1024).toFixed(2)} MiB`,
  );
}
